import { test, expect, browserFixture, serverNotes } from './fixtures';

test('два сотрудника видят общую записку, ответ, координаты, отметки и архив с фильтрами', async ({ page, browser }) => {
  test.setTimeout(90000);
  await page.goto('/');
  const other = await browser.newContext({ viewport: { width: 1242, height: 1266 }, extraHTTPHeaders: { 'x-forwarded-for': '10.100.100.22' } });
  const anna = await other.newPage();
  anna.setDefaultTimeout(12000);
  try {
    await anna.goto('http://127.0.0.1:5174');
    await anna.getByLabel('Логин', { exact: true }).fill('anna');
    await anna.getByLabel('Пароль', { exact: true }).fill(browserFixture.password);
    await anna.getByRole('button', { name: 'Войти', exact: true }).click();
    await expect(anna.getByRole('heading', { level: 1 })).toHaveText('Бухгалтерия');
    await anna.getByRole('button', { name: 'Новый стикер' }).click();
    await anna.getByLabel('Доска', { exact: true }).selectOption(browserFixture.departments.find(department => department.legacyId === 'it')!.boardId);
    await anna.getByLabel('Получатель', { exact: true }).selectOption('employees');
    await anna.getByLabel('Константин', { exact: true }).check();
    await anna.getByLabel('Текст записки').fill('Общая записка двух сотрудников');
    await anna.getByRole('button', { name: 'Закрепить', exact: true }).click();
    const original = anna.locator('.sticky-note').filter({ hasText: 'Общая записка двух сотрудников' });
    await expect(original).toBeVisible();
    const id = (await original.getAttribute('data-note-id'))!;
    const remote = page.locator('[data-note-id="' + id + '"]');
    await expect(remote).toBeVisible({ timeout: 12000 });
    await expect(remote.getByRole('button', { name: 'Изменить', exact: true })).toHaveCount(0);
    await expect(remote.getByLabel('Готово')).toBeDisabled();
    await remote.getByLabel('Прочитано').check();
    await remote.getByLabel('Готово').check();
    await expect(original.getByLabel('Готово')).toBeChecked({ timeout: 12000 });
    await original.getByRole('button', { name: 'Изменить', exact: true }).click();
    await anna.getByLabel('Текст записки').fill('Общая записка двух сотрудников — обновлено');
    await anna.getByRole('button', { name: 'Сохранить', exact: true }).click();
    await expect(remote.locator('.note-message')).toContainText('обновлено', { timeout: 12000 });
    await remote.getByRole('button', { name: 'Ответить', exact: true }).click();
    await page.getByLabel('Ваш ответ').fill('Ответ в общей переписке');
    await page.getByRole('button', { name: 'Закрепить', exact: true }).click();
    await expect(anna.locator('.reply-note').filter({ hasText: 'Ответ в общей переписке' })).toBeVisible({ timeout: 12000 });
    const group = page.locator('[data-group-id="' + id + '"]');
    const before = (await serverNotes(page)).find(note => note.id === id)!.x;
    await remote.locator('.note-drag-handle').focus();
    await page.keyboard.press('Space');
    await expect(group).toHaveClass(/is-dragging/);
    await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => resolve())));
    await page.keyboard.press('ArrowRight');
    await expect(group).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 25, 0)');
    await page.keyboard.press('Space');
    await expect(anna.locator('[data-group-id="' + id + '"]')).toHaveCSS('left', before + 25 + 'px', { timeout: 12000 });
    anna.once('dialog', dialog => { void dialog.accept(); });
    await original.getByRole('button', { name: 'В архив', exact: true }).click();
    await expect(remote).toHaveCount(0, { timeout: 12000 });
    await page.getByRole('button', { name: 'Архив', exact: true }).click();
    await page.getByRole('button', { name: 'Открыть архив: IT-отдел', exact: true }).click();
    await expect(page.locator('.sticky-note')).toHaveCount(2);
    await expect(page.getByRole('button', { name: 'Вернуть на доску' })).toHaveCount(0);
    await page.getByLabel('Отправитель архива').selectOption(browserFixture.employees.find(person => person.legacyId === 'anna')!.id);
    await expect(page.locator('.sticky-note')).toHaveCount(1);
    await page.getByLabel('Отправитель архива').selectOption('');
    await page.getByLabel('Получатель архива').selectOption('employee:' + browserFixture.employees.find(person => person.legacyId === 'anna')!.id);
    await expect(page.locator('.sticky-note')).toHaveCount(2);
    await page.getByLabel('Начало периода архива').fill('2100-01-01');
    await expect(page.locator('.sticky-note')).toHaveCount(0);
    await page.getByLabel('Начало периода архива').fill('');
    await page.screenshot({ path: '.local/archive-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: '.local/archive-mobile.png', fullPage: true, animations: 'disabled' });
    await page.setViewportSize({ width: 1242, height: 900 });
    await anna.getByRole('button', { name: 'Архив', exact: true }).click();
    await anna.getByRole('button', { name: 'Открыть архив: IT-отдел', exact: true }).click();
    await anna.getByRole('button', { name: 'Вернуть на доску', exact: true }).click();
    await anna.getByRole('button', { name: 'IT-отдел SYS' }).click();
    await expect(original).toBeVisible();
    await expect(anna.locator('.reply-note').filter({ hasText: 'Ответ в общей переписке' })).toBeVisible();
    await page.reload();
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('IT-отдел');
    await expect(remote).toBeVisible();
    await expect(remote.getByLabel('Готово')).toBeChecked();
  } finally { await other.close(); }
});
