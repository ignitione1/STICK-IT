import { test, expect } from './fixtures';

test('профиль сохраняет фото, десять дизайнов и независимое крепление для новых записок', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Мой профиль' }).click();
  await expect(page.getByRole('group', { name: 'Стиль стикера', exact: true }).getByRole('button')).toHaveCount(10);
  await page.getByRole('button', { name: 'Бумажный архив', exact: true }).click();
  await expect(page.locator('.profile-live-note .paper-pattern')).toHaveCount(0);
  await page.getByRole('button', { name: 'Женщина', exact: true }).click();
  await expect(page.getByRole('group', { name: 'Аватар', exact: true }).getByRole('button')).toHaveCount(6);
  await page.getByRole('button', { name: 'Женский аватар 2', exact: true }).click();
  await page.getByRole('button', { name: /Космос/ }).click();
  await page.getByRole('button', { name: /^Скрепка/ }).click();
  await page.getByRole('button', { name: 'Сохранить профиль' }).click();
  await expect(page.getByRole('status')).toContainText('Профиль сохранён');
  await page.reload();
  await page.getByRole('button', { name: 'Мой профиль' }).click();
  await expect(page.getByRole('button', { name: 'Женский аватар 2', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByRole('button', { name: /^Скрепка/ })).toHaveAttribute('aria-pressed', 'true');
  const image = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 480; canvas.height = 320;
    const context = canvas.getContext('2d')!; context.fillStyle = '#d8b396'; context.fillRect(0, 0, 480, 320);
    context.fillStyle = '#687962'; context.fillRect(180, 80, 120, 200);
    return canvas.toDataURL('image/png').split(',')[1];
  });
  await page.getByLabel('Своё фото', { exact: true }).setInputFiles({ name: 'portrait.png', mimeType: 'image/png', buffer: Buffer.from(image, 'base64') });
  await expect(page.getByAltText('Ваш аватар')).toHaveAttribute('src', /^data:image\/jpeg;base64,/);
  await page.getByRole('button', { name: 'Сохранить профиль' }).click();
  await expect(page.getByRole('status')).toContainText('Профиль сохранён');
  await expect(page.getByAltText('Ваш аватар')).toHaveAttribute('src', /^\/api\/profile\/avatar\//);
  const photo = await page.getByAltText('Ваш аватар').getAttribute('src');
  const photoResponse = await page.request.get(photo!);
  expect(photoResponse.status()).toBe(200);
  expect(photoResponse.headers()['content-type']).toContain('image/jpeg');
  const anonymous = await page.context().browser()!.newContext();
  try { expect((await anonymous.request.get('http://127.0.0.1:5174' + photo)).status()).toBe(401); }
  finally { await anonymous.close(); }
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: '.local/profile-designs-desktop.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.local/profile-designs-mobile.png', fullPage: true, animations: 'disabled' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole('button', { name: 'К доске' }).click();
  await page.getByRole('button', { name: 'Новый стикер' }).click();
  await page.getByLabel('Текст записки').fill('Мой космический стикер');
  await page.getByRole('button', { name: 'Закрепить', exact: true }).click();
  const note = page.locator('.sticky-note').filter({ hasText: 'Мой космический стикер' });
  await expect(note).toHaveClass(/preset-lavender/);
  await expect(note.locator(':scope > .fastening-clip')).toHaveCount(1);
  await expect(note.locator('.pattern-lavender')).toHaveCount(1);
  await page.getByRole('button', { name: 'Мой профиль' }).click();
  await page.getByRole('button', { name: /Хороший день/ }).click();
  await expect(page.getByRole('button', { name: /^Скрепка/ })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: /^Кнопка/ }).click();
  await page.getByRole('button', { name: 'Сохранить профиль' }).click();
  await expect(page.getByRole('status')).toContainText('Профиль сохранён');
  await page.reload();
  await page.getByRole('button', { name: 'Мой профиль' }).click();
  await expect(page.getByAltText('Ваш аватар')).toHaveAttribute('src', photo!);
  await page.getByRole('button', { name: 'К доске' }).click();
  await expect(note).toHaveClass(/preset-lavender/);
  await expect(note.locator(':scope > .fastening-clip')).toHaveCount(1);
  await page.getByRole('button', { name: 'Новый стикер' }).click();
  await page.getByLabel('Текст записки').fill('Мой персиковый стикер');
  await page.getByRole('button', { name: 'Закрепить', exact: true }).click();
  const newer = page.locator('.sticky-note').filter({ hasText: 'Мой персиковый стикер' });
  await expect(newer).toHaveClass(/preset-peach/);
  await expect(newer.locator('.fastening-pin')).toHaveCount(1);
  await page.getByRole('button', { name: 'Мой профиль' }).click();
  await page.getByRole('button', { name: 'Женщина', exact: true }).click();
  await page.getByRole('button', { name: 'Женский аватар 5', exact: true }).click();
  await page.getByRole('button', { name: 'Сохранить профиль' }).click();
  await expect(page.getByRole('status')).toContainText('Профиль сохранён');
  expect((await page.request.get(photo!)).status()).toBe(404);
});
