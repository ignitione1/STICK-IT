authenticatedTest('администратор редактирует и убирает пустой отдел, сохраняя остальные доски', async ({ page }) => {
  const suffix = Date.now().toString(36);
  const original = `Отдел ${suffix}`;
  const renamed = `Новый отдел ${suffix}`;
  await page.goto('/');
  await page.getByRole('button', { name: 'Управление командой' }).click();
  await page.getByRole('button', { name: /^Отделы/ }).click();
  await page.getByRole('button', { name: 'Добавить отдел' }).click();
  await page.getByLabel('Название отдела').fill(original);
  await page.getByLabel('Код отдела').fill(`empty-${suffix}`);
  await page.getByRole('button', { name: 'Создать отдел' }).click();
  await page.getByRole('button', { name: `Изменить отдел ${original}`, exact: true }).click();
  await page.getByLabel('Название отдела').fill(renamed);
  await page.getByRole('button', { name: 'Сохранить отдел' }).click();
  await expect(page.getByRole('heading', { name: renamed, exact: true })).toBeVisible();
  page.once('dialog', dialog => { void dialog.accept(); });
  await page.getByRole('button', { name: `Удалить отдел ${renamed}`, exact: true }).click();
  await expect(page.getByRole('heading', { name: renamed, exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'К доске' }).click();
  await expect(page.getByRole('button', { name: new RegExp(renamed) })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'IT-отдел SYS' })).toBeVisible();
});

