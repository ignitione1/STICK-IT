import { test, expect, browserFixture } from './fixtures';

test('архив хранит отдельный ответ без активного оригинала и раскрывает стопки по доскам отделов', async ({ page }) => {
  test.setTimeout(90000);
  const it = browserFixture.departments.find(department => department.legacyId === 'it')!.boardId;
  const finance = browserFixture.departments.find(department => department.legacyId === 'accounting')!.boardId;
  await page.goto('/');
  await page.getByRole('button', { name: 'Новый стикер' }).click();
  await page.getByLabel('Текст записки').fill('Исходная записка для нового архива');
  await page.getByRole('button', { name: 'Закрепить', exact: true }).click();
  const root = page.locator('.sticky-note').filter({ hasText: 'Исходная записка для нового архива' });
  const rootId = (await root.getAttribute('data-note-id'))!;
  await root.getByRole('button', { name: 'Ответить', exact: true }).click();
  await page.getByLabel('Ваш ответ').fill('Ответ, архивируемый отдельно');
  await page.getByRole('button', { name: 'Закрепить', exact: true }).click();
  const reply = page.locator('.sticky-note').filter({ hasText: 'Ответ, архивируемый отдельно' });
  const replyId = (await reply.getAttribute('data-note-id'))!;
  await page.setViewportSize({ width: 390, height: 844 });
  for (const name of ['Изменить', 'В архив']) {
    const button = reply.getByRole('button', { name, exact: true });
    await button.scrollIntoViewIfNeeded();
    const size = await button.boundingBox();
    expect(size!.height).toBeGreaterThanOrEqual(38);
    expect(size!.width).toBeGreaterThanOrEqual(44);
  }
  await reply.screenshot({ path: '.local/note-actions-mobile.png', animations: 'disabled' });
  await page.setViewportSize({ width: 1242, height: 900 });
  page.once('dialog', async dialog => { expect(dialog.message()).toContain('этот ответ'); await dialog.accept(); });
  await reply.getByRole('button', { name: 'В архив', exact: true }).click();
  await expect(reply).toHaveCount(0);
  await expect(root).toBeVisible();
  await page.getByRole('button', { name: 'Архив', exact: true }).click();
  await page.getByRole('button', { name: 'Открыть архив: IT-отдел', exact: true }).click();
  await expect(page.locator('[data-note-id="' + rootId + '"]')).toHaveCount(0);
  await expect(page.locator('[data-note-id="' + replyId + '"]')).toBeVisible();
  await page.getByRole('button', { name: 'К исходной записке' }).click();
  await expect(root).toBeVisible();
  await root.getByRole('button', { name: 'Ответить', exact: true }).click();
  await page.getByLabel('Ваш ответ').fill('Ответ, который уйдёт вместе с цепочкой');
  await page.getByRole('button', { name: 'Закрепить', exact: true }).click();
  page.once('dialog', async dialog => { expect(dialog.message()).toContain('всю её цепочку'); await dialog.accept(); });
  await root.getByRole('button', { name: 'В архив', exact: true }).click();
  await expect(root).toHaveCount(0);
  await page.getByRole('button', { name: 'Новый стикер' }).click();
  await page.getByLabel('Доска', { exact: true }).selectOption(finance);
  await page.getByLabel('Текст записки').fill('Записка из другой доски отдела');
  await page.getByRole('button', { name: 'Закрепить', exact: true }).click();
  page.once('dialog', dialog => dialog.accept());
  await page.locator('.sticky-note').filter({ hasText: 'Записка из другой доски отдела' }).getByRole('button', { name: 'В архив', exact: true }).click();
  await page.getByRole('button', { name: 'Архив', exact: true }).click();
  await page.getByRole('button', { name: 'Все отделы', exact: true }).click();
  await expect(page.getByRole('button', { name: /^Открыть архив:/ })).toHaveCount(2);
  const reset = page.getByRole('button', { name: 'Сбросить фильтры' });
  await expect(reset).toBeDisabled();
  await page.getByLabel('Отдел архива').selectOption(it);
  await page.getByLabel('Отправитель архива').selectOption(browserFixture.employees.find(person => person.legacyId === 'konstantin')!.id);
  await page.getByLabel('Получатель архива').selectOption({ index: 1 });
  await page.getByLabel('Начало периода архива').fill('2020-01-01');
  await page.getByLabel('Конец периода архива').fill('2099-12-31');
  await page.getByLabel('Поиск по запискам').fill('не найдётся');
  await reset.click();
  for (const label of ['Отдел архива', 'Отправитель архива', 'Получатель архива', 'Начало периода архива', 'Конец периода архива', 'Поиск по запискам']) {
    await expect(page.getByLabel(label)).toHaveValue('');
  }
  await expect(reset).toBeDisabled();
  await expect(page.getByRole('button', { name: /^Открыть архив:/ })).toHaveCount(2);
  await page.screenshot({ path: '.local/archive-stacks-desktop.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.local/archive-stacks-mobile.png', fullPage: true, animations: 'disabled' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByLabel('Отдел архива').selectOption(finance);
  await expect(page.locator('.archive-grid .sticky-note')).toHaveCount(1);
  await page.getByLabel('Отдел архива').selectOption(it);
  await expect(page.locator('.archive-grid .sticky-note')).toHaveCount(3);
  const grouped = page.locator('.archive-entry').filter({ has: page.locator('[data-note-id="' + rootId + '"]') });
  await expect(grouped.locator('[data-note-id="' + replyId + '"]')).toHaveCount(1);
  await expect(page.locator('.archive-reply-context')).toHaveCount(0);
  await page.screenshot({ path: '.local/archive-unfolded-mobile.png', fullPage: true, animations: 'disabled' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1242, height: 900 });
  await page.screenshot({ path: '.local/archive-unfolded-desktop.png', fullPage: true, animations: 'disabled' });
  const archivedReply = page.locator('[data-note-id="' + replyId + '"]');
  await expect(archivedReply.getByRole('button', { name: 'Вернуть на доску' })).toHaveCount(0);
  await page.locator('[data-note-id="' + rootId + '"]').getByRole('button', { name: 'Вернуть на доску' }).click();
  await expect(page.locator('.archive-grid .sticky-note')).toHaveCount(1);
  await expect(archivedReply.getByRole('button', { name: 'Вернуть на доску' })).toBeVisible();
  await expect(page.locator('.archive-reply-context')).toBeVisible();
  await archivedReply.getByRole('button', { name: 'Вернуть на доску' }).click();
  await expect(page.locator('.archive-grid .sticky-note')).toHaveCount(0);
  await page.getByRole('button', { name: 'IT-отдел SYS' }).click();
  await expect(root).toBeVisible();
  await expect(reply).toBeVisible();
  await page.reload();
  await expect(reply).toBeVisible();
});

test('администратор выборочно удаляет переписку из архива по фильтру', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Новый стикер' }).click();
  await page.getByLabel('Текст записки').fill('Удаляемая переписка');
  await page.getByRole('button', { name: 'Закрепить', exact: true }).click();
  const root = page.locator('.sticky-note').filter({ hasText: 'Удаляемая переписка' });
  await root.getByRole('button', { name: 'Ответить', exact: true }).click();
  await page.getByLabel('Ваш ответ').fill('Ответ без совпадения');
  await page.getByRole('button', { name: 'Закрепить', exact: true }).click();
  page.once('dialog', dialog => dialog.accept());
  await root.getByRole('button', { name: 'В архив', exact: true }).click();
  await page.getByRole('button', { name: 'Архив', exact: true }).click();
  const button = page.getByRole('button', { name: 'Удалить выбранное из архива' });
  await expect(button).toBeDisabled();
  await page.getByLabel('Отдел архива').selectOption(browserFixture.departments.find(item => item.legacyId === 'it')!.boardId);
  await page.getByLabel('Поиск по запискам').fill('Удаляемая переписка');
  await expect(page.getByText('К удалению: 2 (включая ответы)')).toBeVisible();
  page.once('dialog', async dialog => { expect(dialog.message()).toContain('записок: 2'); await dialog.accept(); });
  await button.click();
  await expect(page.getByText('К удалению: 0 (включая ответы)')).toBeVisible();
  const data = await (await page.request.get('/api/stickers')).json();
  expect(data.notes.some((note: { text: string }) => ['Удаляемая переписка', 'Ответ без совпадения'].includes(note.text))).toBe(false);
});
